'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { ACCOUNT_DATA_KEYS, DEFAULT_LIMITS } = require('../src/account-data-store.cjs');

const bridge = fs.readFileSync(path.join(__dirname, '../resources/bridge-preload.cjs'), 'utf8');
const main = fs.readFileSync(path.join(__dirname, '../src/main.cjs'), 'utf8');
const mainEntry = fs.readFileSync(path.join(__dirname, '../src/main-entry.cjs'), 'utf8');
const accountBoundary = fs.readFileSync(path.join(__dirname, '../src/account-data-boundary.cjs'), 'utf8');
const accountStore = fs.readFileSync(path.join(__dirname, '../src/account-data-store.cjs'), 'utf8');
const preload = fs.readFileSync(path.join(__dirname, '../src/preload.cjs'), 'utf8');
const app = fs.readFileSync(path.join(__dirname, '../ui/app.js'), 'utf8');
const adapters = fs.readFileSync(path.join(__dirname, '../ui/translation-adapters.js'), 'utf8');

assert.match(bridge, /ipcRenderer\.sendToHost\(/);
assert.match(bridge, /geek-bridge/);
assert.match(bridge, /__geekBridge/);
assert.match(bridge, /event\.source !== window/);
assert.match(bridge, /data-geek-bridge/);
assert.match(main, /bridge:get-preload-path/);
assert.match(main, /bridge-preload\.cjs/);
assert.match(preload, /preloadPath: \(\) => ipcRenderer\.invoke\('bridge:get-preload-path'\)/);
assert.match(app, /setAttribute\('preload', bridgePreloadPath\)/);
assert.match(app, /account\.type !== 'line' && account\.type !== 'line-business'/);
assert.match(app, /handleGeekBridgeIpc/);
assert.match(app, /data-geek-bridge/);
assert.match(app, /window\.postMessage\(\{ __geekBridge: true/);
assert.match(app, /TRANSLATION_REQUEST_PREFIX/);
assert.match(app, /NATIVE_INPUT_REQUEST_PREFIX/);
assert.match(adapters, /data-geek-bridge/);
assert.match(adapters, /native-input-request/);
assert.match(main, /translation:translate/);
assert.match(main, /concurrency|并发|MAX_CONCURRENT|Semaphore|queue/i);
assert.match(adapters, /translateHistory|transOldHistory|history/);
assert.doesNotMatch(adapters + main + app, /快捷话术|quickPhrase|quick-phrase/i);

assert.doesNotMatch(mainEntry, /installAccountDataBoundary\(/, 'account data is no longer a startup registration shim');
assert.match(main, /const accountDataBoundary = installAccountDataBoundary\(/, 'main composition installs the account-data owner explicitly');
assert.match(accountBoundary, /register\('account-data:get-all'/);
assert.match(accountBoundary, /register\('account-data:set'/);
assert.match(accountBoundary, /register\('account-data:remove'/);
assert.match(accountBoundary, /runAccountRemoval/);
assert.match(accountBoundary, /ACCOUNT_DATA_SENDER_INVALID/);
assert.match(accountStore, /ACCOUNT_DATA_KEY_NOT_ALLOWED/);
assert.match(accountStore, /ACCOUNT_DATA_LOG_CORRUPT/);
assert.match(accountStore, /\.compact\.tmp/);
assert.equal(DEFAULT_LIMITS.maxValueBytes, 2 * 1024 * 1024);
assert.equal(DEFAULT_LIMITS.compactRecordCount, 512);
assert.equal(DEFAULT_LIMITS.compactFileBytes, 64 * 1024 * 1024);
const sandboxKeysMatch = app.match(/const ACCOUNT_SANDBOX_KEYS = \[([^\]]+)\]/);
assert.ok(sandboxKeysMatch);
const rendererKeys = [...sandboxKeysMatch[1].matchAll(/'([^']+)'/g)].map(match => match[1]).sort();
const mainKeys = ACCOUNT_DATA_KEYS.filter(key => key !== '__schema').sort();
assert.deepEqual(rendererKeys, mainKeys);

console.log('BRIDGE_IPC_CONTRACT_OK');
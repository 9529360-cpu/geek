'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const app = fs.readFileSync(path.join(root, 'ui/app.js'), 'utf8');
const hostAdapters = fs.readFileSync(path.join(root, 'ui/platform-host-adapters.js'), 'utf8');
const preload = fs.readFileSync(path.join(root, 'resources/bridge-preload.cjs'), 'utf8');
const webview = fs.readFileSync(path.join(root, 'src/webview-ipc.cjs'), 'utf8');
const mainHelper = fs.readFileSync(path.join(root, 'src/whatsapp-webview-send-intent.cjs'), 'utf8');
const capability = fs.readFileSync(path.join(root, 'ui/whatsapp-send-intent-capability.js'), 'utf8');
const controller = fs.readFileSync(path.join(root, 'ui/whatsapp-direct-composer-controller.js'), 'utf8');

assert.match(app, /family === 'whatsapp'/);
assert.match(app, /executePlatformOutgoingSendIntent/);
assert.ok(app.includes('whatsapp: window.GeekWhatsAppSendIntentCapability'), 'app composition must inject the WhatsApp family capability into the host adapter registry');
assert.match(hostAdapters, /factories\.set\('whatsapp'[\s\S]*whatsapp\.sendText/);
assert.match(app, /sendIntentOwnerHealthy[\s\S]*version \|\| 0\) >= 9[\s\S]*submitThroughOwner/);
assert.match(app, /data-geek-native-submit-commit[\s\S]*return false/);
assert.doesNotMatch(app, /const wrappedSendText = function|__geekSendQueue\.then|sendTextMsgToChat = wrappedSendText/);
assert.doesNotMatch(app, /NO_SEND_MODULE/, 'interactive WhatsApp send readiness must not depend on the removed WA-JS text hook');
assert.match(app, /mod\?\.__geekOriginalSendText[\s\S]*mod\.sendTextMsgToChat = mod\.__geekOriginalSendText/);
assert.match(app, /WAWebMediaPrep[\s\S]*sendMediaMsgToChat/, 'media caption path must remain independent');
assert.match(preload, /platform:\s*'whatsapp'/);
assert.match(preload, /event\?\.isTrusted !== true/);
assert.match(preload, /TRUSTED_SUBMIT_CHANNEL/);
assert.match(preload, /NATIVE_COMMIT_MARKER/);
assert.match(webview, /whatsappSendIntent\.isWhatsAppType/);
assert.match(webview, /whatsappSendIntent\.commitGuardScript/);
assert.match(mainHelper, /currentChat\s*!==\s*expected\.conversationId/);
assert.match(mainHelper, /COMPOSER_MISMATCH/);
assert.match(mainHelper, /data-geek-native-submit-commit/);
assert.match(capability, /webviewInput\.commitSubmit/);
assert.match(capability, /state\?\.count > baseline\.count && state\?\.empty === true/);
assert.match(capability, /return 'MAYBE'/);
assert.doesNotMatch(capability, /chat\.sendTextMessage/);
assert.match(controller, /delivery\?\.owner !== 'send-intent'/);
assert.doesNotMatch(controller, /nativeQueue|handleNativeSend|sendTextMessage\(|sendTextMsgToChat/);
console.log('WHATSAPP_SEND_INTENT_OWNER_CONTRACT_OK');

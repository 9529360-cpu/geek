use serde::Serialize;
use std::fmt;

pub type Result<T> = std::result::Result<T, AppError>;

/// Stable IPC codes only: never serialize native errors, URLs or user data.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]

'use strict';

// Physical lines include comments and blanks. Generated Cargo.lock is data, not
// handwritten code. Never raise this cap or pack code to work around it.
const MAX_LINES = 3000;
const REVIEW_LINES = 500;
const MAX_SCRIPT_WIDTH = 180;
const CODE = /\.(?:rs|[cm]?js|[cm]?ts|jsx|tsx|html|css|scss|json|toml|ya?ml|ps1|py|sh)$/i;
const GENERATED_DIRS = new Set(['src-tauri/target', 'src-tauri/gen', 'src-tauri/permissions/autogenerated', 'node_modules', '.git']);

function lineCount(text) {
  const normalized = text.replace(/\r\n?/g, '\n');
  if (!normalized) return 0;
  return normalized.split('\n').length - Number(normalized.endsWith('\n'));
}

function maskNonCode(source) {
  // Lexical architecture guard, not a substitute for the compiler/security review.
  return source.replace(/"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\\n])*'|\/\/[^\n]*|\/\*[\s\S]*?\*\//g,
    (match) => match.replace(/[^\n]/g, ' '));
}

function checkFile(path, source) {
  const failures = [];
  if (!CODE.test(path)) return failures;
  if (lineCount(source) > MAX_LINES) failures.push(`${path}: exceeds ${MAX_LINES} physical lines`);
  if (source.includes('\r')) failures.push(`${path}: use LF line endings`);
  if (source && !source.endsWith('\n')) failures.push(`${path}: missing final newline`);
  if (/[^\S\n]+$/m.test(source)) failures.push(`${path}: trailing whitespace`);
  if (/\.(?:[cm]?js|css)$/.test(path)
      && source.split('\n').some((line) => [...line].length > MAX_SCRIPT_WIDTH)) {
    failures.push(`${path}: packed/long line exceeds ${MAX_SCRIPT_WIDTH} characters`);
  }
  const code = maskNonCode(source);
  if (path.startsWith('src-tauri/src/domain/')) {
    if (/\b(?:tauri|tokio|reqwest|application|infrastructure|desktop|fs|process)\b/.test(code)) {
      failures.push(`${path}: domain must not depend on application, native, storage or network code`);
    }
  }
  if (path.startsWith('src-tauri/src/application/')) {
    if (/\b(?:tauri|tokio|reqwest|infrastructure|desktop|fs|process)\b/.test(code)
        || /crate\s*::\s*desktop\b/.test(code)) {
      failures.push(`${path}: application must depend on ports/domain, not native implementations`);
    }
  }
  if (path.startsWith('src-tauri/src/infrastructure/')) {
    if (/\b(?:tauri|desktop)\b/.test(code)
        || /application\s*::\s*(?!ports\b)\w+/.test(code)) {
      failures.push(`${path}: infrastructure may implement application ports, not call desktop use cases`);
    }
  }
  if (path.endsWith('.rs') && !path.includes('/tests/') && !path.endsWith('/dpapi.rs')
      && /\bunsafe\s*(?:\{|fn|impl|trait|extern)/.test(code)) {
    failures.push(`${path}: unsafe is restricted to the reviewed Windows DPAPI adapter`);
  }
  if (path.startsWith('frontend/') && /\.[cm]?js$/.test(path)) {
    if (path !== 'frontend/api/desktop.mjs' && /__TAURI__|\binvoke\s*\(/.test(source)) {
      failures.push(`${path}: native bridge access belongs only in frontend/api/desktop.mjs`);
    }
    if (/\b(?:innerHTML|insertAdjacentHTML)\b|\beval\s*\(|\bnew\s+Function\s*\(/.test(code)) {
      failures.push(`${path}: unsafe DOM/code evaluation is prohibited`);
    }
  }
  if (path.startsWith('src-tauri/src/') && path.endsWith('.rs')) {
    const relative = path.slice('src-tauri/src/'.length);
    if (!/^(?:main\.rs|bootstrap\.rs|(?:domain|application|infrastructure|desktop|tests)\/)/.test(relative)) {
      failures.push(`${path}: source has no architectural owner`);
    }
    if (/\binclude\s*!|#\s*\[\s*path\s*=/.test(code)) {
      failures.push(`${path}: source-inclusion escape bypasses declared ownership`);
    }
  }
  return failures;
}

module.exports = { MAX_LINES, REVIEW_LINES, CODE, GENERATED_DIRS, lineCount, checkFile };
